package com.lb_calc_web.domain.model;

/**
 * Ячейка модуля хранения.
 *
 * <p>Ячейка принадлежит конкретному {@link StorageModule}.
 * Её номер не является постоянным свойством самой ячейки:
 * номер определяется положением ячейки внутри конкретного
 * {@link ALS} и назначается агрегатом ALS.</p>
 *
 * <p>Поэтому при создании ячейки номер не задаётся. После формирования
 * конфигурации ALS ячейки последовательно нумеруются слева направо
 * по порядку модулей и ячеек.</p>
 */
public class StorageCell {

    private int number;

    /**
     * Создаёт ячейку без номера.
     *
     * <p>Конструктор доступен только внутри domain-пакета.
     * Номер назначается позже агрегатом {@link ALS}.</p>
     */
    StorageCell() {
    }

    /**
     * Возвращает номер ячейки в конкретном ALS.
     *
     * @return положительный номер ячейки
     */
    public int getNumber() {
        return number;
    }

    /**
     * Назначает номер ячейки.
     *
     * <p>Метод намеренно не является публичным: номер должен
     * управляться доменной моделью ALS, а не произвольным внешним кодом.</p>
     *
     * @param number положительный номер ячейки
     * @throws IllegalArgumentException если номер меньше или равен нулю
     */
    void setNumber(int number) {
        if (number <= 0) {
            throw new IllegalArgumentException(
                    "Номер ячейки должен быть положительным"
            );
        }

        this.number = number;
    }

    /**
     * Возвращает строковое представление ячейки.
     *
     * @return номер ячейки
     */
    @Override
    public String toString() {
        return "StorageCell{" +
                "number=" + number +
                '}';
    }
}
